#!/usr/bin/env python3
"""Generate assets/css/gameday-site-chrome.css from the parent's swat-flagship.css.

Game Day (1.0.17+) is styled by assets/css/swat-gameday-hub.css. The parent's
flagship stylesheet also carries ~200 Game Day component rules (most with
!important) that would fight the hub, but Game Day still needs flagship's
site-wide rules (site header, mobile menu, buttons, base type).

This script copies swat-flagship.css and removes only selectors that target
Game Day components. Everything else is kept byte-for-byte, in order. On Game
Day requests inc/gameday-hub.php prints this file instead of swat-flagship.css.
Other pages keep loading the parent's flagship file unchanged.

Re-run after a parent update (tests/run-all.sh checks that the file is current):
  tools/build-gameday-chrome.py /path/to/parent-theme > assets/css/gameday-site-chrome.css
"""
import os, re, sys

GAMEDAY = re.compile(
    r'swat-gameday|swat-game-|swat-app-|swat-bottom-nav|swat-team-picker|swat-team-pick|'
    r'swat-my-weekend|swat-itinerary|swat-path-|swat-team-path|swat-standing|swat-bracket|'
    r'swat-field-card|swat-field-grid|swat-weather|swat-more-grid|swat-home-|swat-alert|'
    r'swat-followed|swat-next-|swat-status-pill|swat-championship|swat-day-tabs|swat-filter-bar|'
    r'swat-quick-actions|swat-postseason|swat-pitch|swat-appearance|swat-ux|swat-context|'
    r'swat-matchup|swat-team-row|swat-smart-alert|swat-weekend|swat-install-link|swat-updated|'
    r'swat-empty-state|swat-mobile-form|swat-score-entry|swat-issue|swat-form-|swat-clear-filters|'
    r'swat-team-search|swat-picker|swat-team-tone|swat-section-gap|swat-icon-button|swat-live-dot|'
    r'data-swat-'
)


def blocks(css):
    """Yield (header, body, raw) for each top-level block; comments are kept as text."""
    i, n = 0, len(css)
    while i < n:
        j = css.find('{', i)
        if j < 0:
            tail = css[i:]
            if tail.strip():
                yield None, None, tail
            return
        header = css[i:j]
        depth, k = 1, j + 1
        while k < n and depth:
            c = css[k]
            if c == '/' and css.startswith('/*', k):
                end = css.find('*/', k + 2)
                k = (end + 2) if end >= 0 else n
                continue
            depth += (c == '{') - (c == '}')
            k += 1
        yield header, css[j + 1:k - 1], css[i:k]
        i = k


def split_selectors(header):
    parts, depth, cur = [], 0, ''
    for ch in header:
        if ch in '([':
            depth += 1
        elif ch in ')]':
            depth -= 1
        if ch == ',' and depth == 0:
            parts.append(cur)
            cur = ''
        else:
            cur += ch
    parts.append(cur)
    return parts


def strip_comments(text):
    return re.sub(r'/\*.*?\*/', '', text, flags=re.S)


def filter_css(css):
    out = []
    for header, body, raw in blocks(css):
        if header is None:
            out.append(raw)
            continue
        lead = header[: len(header) - len(header.lstrip())]
        head = header.strip()
        comment = ''
        m = re.match(r'^((?:\s*/\*.*?\*/\s*)+)(.*)$', head, flags=re.S)
        if m:
            comment, head = m.group(1), m.group(2).strip()
        if head.startswith('@media') or head.startswith('@supports'):
            inner = filter_css(body)
            if strip_comments(inner).strip():
                out.append(lead + comment + head + '{' + inner + '}')
            continue
        if head.startswith('@'):
            out.append(raw)
            continue
        kept = [s for s in split_selectors(head) if not GAMEDAY.search(s)]
        if kept:
            out.append(lead + comment + ','.join(s.strip() for s in kept) + '{' + body + '}')
    return ''.join(out)


def main():
    parent = sys.argv[1]
    src = os.path.join(parent, 'assets', 'css', 'swat-flagship.css')
    with open(src, encoding='utf-8') as fh:
        css = fh.read()
    sys.stdout.write('/* GENERATED by tools/build-gameday-chrome.py from the parent swat-flagship.css.\n'
                     ' * Game Day component selectors removed; loaded on Game Day only. Do not edit by hand. */\n')
    sys.stdout.write(filter_css(css).strip() + '\n')


if __name__ == '__main__':
    main()
